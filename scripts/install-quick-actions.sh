#!/bin/bash
# Builds ~/Library/Services/Fingerlock.workflow — one Finder right-click item that
# seals plain files and unseals .fingerlock ones.
#
# Quick Actions run with no terminal, so anything the user needs to see has to go
# through osascript. Touch ID puts up its own system dialog.
set -euo pipefail

FINGERLOCK="${FINGERLOCK:-$HOME/.local/bin/fingerlock}"
SERVICE="$HOME/Library/Services/Fingerlock.workflow"

if [ ! -x "$FINGERLOCK" ]; then
	echo "no fingerlock binary at $FINGERLOCK — run 'make install' first" >&2
	exit 1
fi

rm -rf "$SERVICE"
mkdir -p "$SERVICE/Contents"

cat > "$SERVICE/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>NSServices</key>
	<array>
		<dict>
			<key>NSMenuItem</key>
			<dict>
				<key>default</key>
				<string>Fingerlock</string>
			</dict>
			<key>NSMessage</key>
			<string>runWorkflowAsService</string>
			<key>NSRequiredContext</key>
			<dict>
				<key>NSApplicationIdentifier</key>
				<string>com.apple.finder</string>
			</dict>
			<key>NSSendFileTypes</key>
			<array>
				<string>public.item</string>
			</array>
		</dict>
	</array>
</dict>
</plist>
PLIST

# The action body. Escaped into the plist below, so keep it free of ]]> and &.
SCRIPT=$(cat <<SH
for f in "\$@"; do
  if ! out=\$("$FINGERLOCK" toggle "\$f" 2>&1); then
    osascript -e "display alert \"Fingerlock\" message \"\$out\" as critical"
    exit 1
  fi
done
osascript -e 'display notification "Done" with title "Fingerlock"'
SH
)

# Escape for XML.
esc() { python3 -c 'import sys,html; sys.stdout.write(html.escape(sys.stdin.read()))'; }
SCRIPT_XML=$(printf '%s' "$SCRIPT" | esc)

